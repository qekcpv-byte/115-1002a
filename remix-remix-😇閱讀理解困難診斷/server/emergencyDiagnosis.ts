export function determineEffectiveGradeAndUnit(
  unit: string,
  userGrade: string,
  fileName: string,
  contextText: string = ""
): { effectiveGrade: string; cleanedUnit: string; isCalibrated: boolean } {
  let cleanedUnit = (unit || fileName || "")
    .replace(/\.(docx|doc|pdf|png|jpg|jpeg|webp|gif|txt|md)$/i, "")
    .replace(/^檔案分析[:：]\s*/, "")
    .trim();

  const combined = `${cleanedUnit} ${fileName || ""} ${contextText || ""}`.toLowerCase();

  let detectedGrade = "";

  // 1. Check 會考 / 基測 / 國中三年級 / 國三 first
  if (
    combined.includes("會考") ||
    combined.includes("基測") ||
    combined.includes("教育會考") ||
    combined.includes("國三") ||
    combined.includes("九年級") ||
    combined.includes("112") ||
    combined.includes("疫苗") ||
    (combined.includes("國中") && combined.includes("三年級"))
  ) {
    detectedGrade = "國中教育會考（九年級）";
    if (
      combined.includes("112") ||
      combined.includes("疫苗") ||
      combined.includes("安慰劑")
    ) {
      if (!cleanedUnit || cleanedUnit === "數學閱讀理解單元" || cleanedUnit.startsWith("檔案分析") || cleanedUnit.includes("112")) {
        cleanedUnit = "112數學會考#1（疫苗效力與代數素養題）";
      }
    } else if (
      combined.includes("107") &&
      (combined.includes("#1") || combined.includes("第1題") || combined.includes("第一題") || combined.includes("1題") || combined.includes("對稱"))
    ) {
      if (!cleanedUnit || cleanedUnit === "數學閱讀理解單元" || cleanedUnit.startsWith("檔案分析")) {
        cleanedUnit = "107數學會考#1（線對稱圖形）";
      }
    }
  } else if (
    combined.includes("垂直平分線") ||
    combined.includes("中垂線") ||
    combined.includes("線對稱") ||
    combined.includes("畢氏定理") ||
    combined.includes("勾股定理") ||
    combined.includes("乘法公式") ||
    combined.includes("八年級") ||
    combined.includes("國二") ||
    (combined.includes("國中") && combined.includes("二年級"))
  ) {
    detectedGrade = "國中八年級";
  } else if (
    combined.includes("一元一次") ||
    combined.includes("二元一次") ||
    combined.includes("負數與絕對值") ||
    combined.includes("七年級") ||
    combined.includes("國一") ||
    (combined.includes("國中") && combined.includes("一年級"))
  ) {
    detectedGrade = "國中七年級";
  } else if (
    combined.includes("相似形") ||
    combined.includes("二次函數") ||
    combined.includes("圓形定理")
  ) {
    detectedGrade = "國中九年級";
  } else if (
    combined.includes("三角函數") ||
    combined.includes("多項式") ||
    combined.includes("高中") ||
    combined.includes("學測") ||
    combined.includes("分科")
  ) {
    detectedGrade = "高中十年級";
  } else if (
    combined.includes("萬以內的數") ||
    combined.includes("千以內的數") ||
    combined.includes("百以內的數") ||
    combined.includes("四位數") ||
    combined.includes("定位板") ||
    (combined.includes("國小") && combined.includes("三年級")) ||
    (!combined.includes("國中") && !combined.includes("高中") && (combined.includes("三年級") || combined.includes("中年級")))
  ) {
    detectedGrade = "國小三年級";
    if (!cleanedUnit || cleanedUnit === "數學閱讀理解單元" || cleanedUnit.startsWith("檔案分析")) {
      cleanedUnit = "萬以內的數";
    }
  } else if (
    combined.includes("10以內的數") ||
    combined.includes("20以內的數") ||
    (combined.includes("國小") && combined.includes("一年級"))
  ) {
    detectedGrade = "國小一年級";
  } else if (
    combined.includes("乘法") &&
    (combined.includes("九九") || combined.includes("二年級") || (combined.includes("國小") && combined.includes("二年級")))
  ) {
    detectedGrade = "國小二年級";
  } else if (
    combined.includes("概數") ||
    combined.includes("億以內的數") ||
    (combined.includes("國小") && combined.includes("四年級"))
  ) {
    detectedGrade = "國小四年級";
  } else if (
    combined.includes("因數") ||
    combined.includes("倍數") ||
    (combined.includes("國小") && combined.includes("五年級"))
  ) {
    detectedGrade = "國小五年級";
  } else if (
    combined.includes("基準量") ||
    combined.includes("比較量") ||
    combined.includes("比與比值") ||
    (combined.includes("國小") && combined.includes("六年級"))
  ) {
    detectedGrade = "國小六年級";
  }

  if (!cleanedUnit || cleanedUnit === "數學閱讀理解單元") {
    cleanedUnit = detectedGrade.includes("國中") ? "國中數學幾何與閱讀理解" : "萬以內的數";
  }

  const isUserGradeAuto =
    !userGrade ||
    userGrade === "未指定年級" ||
    userGrade.includes("自動") ||
    userGrade === "auto";

  let effectiveGrade = userGrade;
  let isCalibrated = false;

  if (isUserGradeAuto) {
    effectiveGrade = detectedGrade || (combined.includes("會考") ? "國中教育會考（九年級）" : "國中八年級");
    isCalibrated = true;
  } else {
    // If user's selected grade conflicts with obvious 會考 topic, calibrate to 會考
    if (
      (combined.includes("會考") || combined.includes("基測") || combined.includes("107數學會考")) &&
      userGrade.startsWith("國小")
    ) {
      effectiveGrade = detectedGrade || "國中教育會考（九年級）";
      isCalibrated = true;
    } else {
      effectiveGrade = userGrade;
    }
  }

  if (
    !effectiveGrade ||
    effectiveGrade.includes("自動") ||
    effectiveGrade === "未指定年級"
  ) {
    effectiveGrade = detectedGrade || "國中八年級";
  }

  return { effectiveGrade, cleanedUnit, isCalibrated };
}

